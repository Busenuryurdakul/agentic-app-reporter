export function loadScenariosFromFile(path, fs) {
  if (!path) return SCENARIOS;
  const raw = fs.readFileSync(path, "utf8");
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed)) throw new Error("scenario-file must be a JSON array");
  return parsed;
}

export function selectScenarios(all, { count, startIndex, scenarioKeys }) {
  if (scenarioKeys?.length) {
    const picked = [];
    for (const key of scenarioKeys) {
      const hit = all.find((s) => s.key === key);
      if (!hit) throw new Error(`scenario key not found: ${key}`);
      picked.push(hit);
    }
    return picked;
  }
  const start = startIndex - 1;
  if (start >= all.length) {
    throw new Error(`start-index ${startIndex} exceeds scenario pool size ${all.length}`);
  }
  const slice = all.slice(start, start + count);
  if (slice.length < count) {
    throw new Error(
      `requested count ${count} from start-index ${startIndex} exceeds available scenarios (${slice.length} remaining)`,
    );
  }
  return slice;
}

export function categoryDistribution(scenarios) {
  const out = {};
  for (const s of scenarios) {
    out[s.category] = (out[s.category] || 0) + 1;
  }
  return out;
}
